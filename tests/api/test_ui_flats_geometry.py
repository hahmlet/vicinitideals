def _canon(value: dict[str, object]) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def test_outline_and_plan_geometry_golden_outputs_are_stable() -> None:
    for name, (geojson, drawing) in _cases().items():
        outline = ui._outline(geojson)
        plan = ui._plan(geojson, drawing)
        assert outline == _EXPECTED[name]["outline"]
        assert plan == _EXPECTED[name]["plan"]
        assert _canon(outline) == _canon(_EXPECTED[name]["outline"])
        assert _canon(plan) == _canon(_EXPECTED[name]["plan"])
